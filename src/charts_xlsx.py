    cd.cell(row=r0 + 2, column=8, value="Editable XoL assumptions from IGR XoL parameters.").font = F_CAP
    ded_ref = f"$I${r0}"; lim_ref = f"$I${r0 + 1}"
    h = _hdr_row(cd, r0 + 1, 2, ["Scenario", "Retained within deductible", "Ceded to XoL", "Above tower", "Attachment"])
