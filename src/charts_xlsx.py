def _table_group_shape(cd, summary_name, r0, rows):
    cd.cell(row=r0, column=2, value="1. Group risk shape — gross loss by entity & scenario").font = F_SECT
    h = _hdr_row(cd, r0 + 1, 2, ["Scenario", "FIHL", "FUL", "FIBL", "FIID"])
    sref = _sheet_ref(summary_name)
    for i, scen in enumerate(SCEN_ORDER):
        rr = h + i
        cd.cell(row=rr, column=2, value=scen).font = F_CELL
        for j, ent in enumerate(["FIHL", "FUL", "FIBL", "FIID"], start=3):
            sr = rows[ent] + i
            c = cd.cell(row=rr, column=j, value=f"={sref}!D{sr}")
            c.number_format = MONEY; c.font = F_CELL
        _alt_row(cd, rr, 2, 6, i % 2 == 0)
    return h, h + len(SCEN_ORDER) - 1


def _table_group_gross_net(cd, summary_name, r0, rows, binding=None):
    """FIHL (group) gross & net by scenario — the capital-basis risk shape."""
    cd.cell(row=r0, column=2,
            value="1. Group risk shape — gross vs net loss by scenario (FIHL)").font = F_SECT
    h = _hdr_row(cd, r0 + 1, 2, ["Scenario", "Gross", "Net"])
    sref = _sheet_ref(summary_name)
    for i, scen in enumerate(SCEN_ORDER):
        rr = h + i
        sr = rows["FIHL"] + i
        label = f"{scen}  \u25c6" if scen == binding else scen
        cd.cell(row=rr, column=2, value=label).font = F_CELL
        cd.cell(row=rr, column=3, value=f"={sref}!D{sr}").number_format = MONEY
        cd.cell(row=rr, column=4, value=f"={sref}!J{sr}").number_format = MONEY
        cd.cell(row=rr, column=3).font = F_CELL; cd.cell(row=rr, column=4).font = F_CELL
        _alt_row(cd, rr, 2, 4, i % 2 == 0)
    return h, h + len(SCEN_ORDER) - 1


def _table_pareto(cd, sw_name, sw_ws, r0, n=10):
    cd.cell(row=r0, column=2, value="2. Manufacturer concentration — Space Weather basis").font = F_SECT
    h = _hdr_row(cd, r0 + 1, 2, ["Bus manufacturer", "Exposure", "Cumulative %"])
    swref = _sheet_ref(sw_name)
    total_row = _find_row(sw_ws, "TOTAL", col=2, default=33, exact=False)
    total_ref = f"{swref}!$C${total_row}"
    for i in range(n):
        sr = 6 + i
        rr = h + i
        cd.cell(row=rr, column=2, value=f"={swref}!B{sr}").font = F_CELL
        cd.cell(row=rr, column=3, value=f"={swref}!C{sr}").number_format = MONEY
        cd.cell(row=rr, column=4, value=f"=IFERROR(SUM($C${h}:$C{rr})/{total_ref},0)").number_format = PCT
        cd.cell(row=rr, column=3).font = F_CELL; cd.cell(row=rr, column=4).font = F_CELL
        _alt_row(cd, rr, 2, 4, i % 2 == 0)
    return h, h + n - 1


def _table_delta(cd, changes_name, r0):
    cd.cell(row=r0, column=2, value="3. Gross Δ% by entity & scenario").font = F_SECT
    h = _hdr_row(cd, r0 + 1, 2, ["Scenario", "FIHL", "FUL", "FIBL", "FIID"])
    cref = _sheet_ref(changes_name)
    # Changes tab generated table is Scenario/FIHL/FUL/FIBL/FIID in B7:F13.
    for i in range(5):
        src = 8 + i
        rr = h + i
        cd.cell(row=rr, column=2, value=f"={cref}!B{src}").font = F_CELL
        for c in range(3, 7):
            src_col = get_column_letter(c)
            # Source cells are live numeric Δ% formulas (the ▲/▼ is just a number
            # format), so reference them directly; a no-data '–' coerces to 0.
            formula = f"=IF(ISNUMBER({cref}!{src_col}{src}),{cref}!{src_col}{src},0)"
            cell = cd.cell(row=rr, column=c, value=formula)
            cell.number_format = PCT; cell.font = F_CELL
        _alt_row(cd, rr, 2, 6, i % 2 == 0)
    return h, h + 4


def _table_exposure_bridge(cd, portfolio_name, portfolio_ws, r0):
    cd.cell(row=r0, column=2, value="4. Portfolio in-force exposure bridge").font = F_SECT
    h = _hdr_row(cd, r0 + 1, 2, ["Step", "Exposure movement"])
    pref = _sheet_ref(portfolio_name)
    rows = _find_portfolio_bridge_rows(portfolio_ws)
    # User-facing order requested: Q4 opening -> written/new -> renewed/revaluation -> expired/run-off -> Q1 closing.
    steps = [
        ("Opening", "Opening", rows["Opening"]),
        ("Written / new", "Written", rows["Written"]),
        ("Renewed / revaluation", "Renewed", rows["Renewed"]),
        ("Expired / run-off", "Expired", rows["Expired"]),
        ("Closing", "Closing", rows["Closing"]),
    ]
    for i, (label, _, src_row) in enumerate(steps):
        rr = h + i
        cd.cell(row=rr, column=2, value=label).font = F_CELL
        c = cd.cell(row=rr, column=3, value=f"={pref}!D{src_row}")
        c.number_format = MONEY; c.font = F_CELL
        _alt_row(cd, rr, 2, 3, i % 2 == 0)
    return h, h + len(steps) - 1


