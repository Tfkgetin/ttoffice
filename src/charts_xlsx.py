def _table_tower(cd, summary_name, r0, entity, ded, limit, er0):
    cd.cell(row=r0, column=2, value=f"{entity} — XoL tower utilisation").font = F_SECT
    cd.cell(row=r0, column=8, value="Deductible").font = F_SUB
