# ---- helpers ----------------------------------------------------------------
def _sheet_ref(name: str) -> str:
    return "'" + str(name).replace("'", "''") + "'"


def _safe_delete(wb, sheet_name):
    if sheet_name in wb.sheetnames:
        del wb[sheet_name]


def _locate_entity_rows(ws):
    found = {}
    for r in range(1, (ws.max_row or 40) + 1):
        v = ws.cell(row=r, column=2).value
        if v in ENTITY_ROW0 and v not in found:
            found[v] = r + 2
    return {**ENTITY_ROW0, **found}


def _find_row(ws, label, col=2, default=None, exact=True):
    for r in range(1, ws.max_row + 1):
        v = ws.cell(row=r, column=col).value
        if exact and v == label:
            return r
        if not exact and isinstance(v, str) and label in v:
            return r
    return default


def _find_portfolio_bridge_rows(ws):
    """Locate the live portfolio bridge rows on Portfolio tab.

    Returns source rows for opening/new/run-off/revaluation/closing. The row
    labels are generated by the pipeline and remain formula-linked; this helper
    only locates the rows so Chart Data can point to them.
    """
    labels = {
        "Opening": ["Opening in-force"],
        "Written": ["+ New business", "Written"],
        "Expired": ["− Run-off / expiry", "- Run-off / expiry", "Expired", "Dropped"],
        "Renewed": ["± Revaluation", "Renewed", "Revaluation"],
        "Closing": ["Closing in-force", "Closing"],
    }
    out = {}
    for key, patterns in labels.items():
        for r in range(1, ws.max_row + 1):
            v = ws.cell(row=r, column=2).value
            if isinstance(v, str) and any(p in v for p in patterns):
                out[key] = r
                break
    # sensible generated-workbook defaults
    return {
        "Opening": out.get("Opening", 9),
        "Written": out.get("Written", 10),
        "Expired": out.get("Expired", 11),
        "Renewed": out.get("Renewed", 12),
        "Closing": out.get("Closing", 13),
    }


def _hdr_row(ws, r, c0, headers):
    for j, h in enumerate(headers):
        cell = ws.cell(row=r, column=c0 + j, value=h)
        cell.font = F_HDR
        cell.fill = FILL_HDR
        cell.alignment = Alignment(horizontal="left" if j == 0 else "right", vertical="center")
    return r + 1


def _alt_row(ws, r, c0, c1, alt=False):
    for c in range(c0, c1 + 1):
        cell = ws.cell(row=r, column=c)
        cell.border = Border(bottom=Side(style="thin", color=RULE))
        if alt:
            cell.fill = FILL_ALT


def _style_axes(chart, y_title="$m", y_fmt=MONEY_M):
    chart.x_axis.delete = False
    chart.y_axis.delete = False
    chart.y_axis.title = y_title
    chart.y_axis.numFmt = y_fmt
    chart.y_axis.majorGridlines = ChartLines()
    chart.y_axis.majorGridlines.spPr = GraphicalProperties()
    chart.y_axis.majorGridlines.spPr.line = LineProperties(solidFill=RULE, w=6350)
    chart.x_axis.majorGridlines = None


def _colour(series, rgb, line=None):
    series.graphicalProperties = GraphicalProperties(solidFill=rgb)
    # Bars (line=None) get a thin white edge so adjacent/stacked fills read as
    # separate marks (2px surface-gap spec); line series keep their own colour.
    edge = line if line is not None else "FFFFFF"
    w = 9525 if line is not None else 12700
    series.graphicalProperties.line = LineProperties(solidFill=edge, w=w)


def _safe_num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def _caption(ws, row, text):
    c = ws.cell(row=row, column=2, value=text)
    c.font = F_SECT
    c.alignment = Alignment(wrap_text=True, vertical="top")
    ws.merge_cells(start_row=row, start_column=2, end_row=row + 1, end_column=11)
    ws.row_dimensions[row].height = 24
    ws.row_dimensions[row + 1].height = 18


def _note(ws, row, text):
    c = ws.cell(row=row, column=3, value=text)
    c.font = F_CAP
    c.alignment = Alignment(wrap_text=True, vertical="top")
    ws.merge_cells(start_row=row, start_column=3, end_row=row + 1, end_column=11)
    ws.row_dimensions[row].height = 18
    ws.row_dimensions[row + 1].height = 18

